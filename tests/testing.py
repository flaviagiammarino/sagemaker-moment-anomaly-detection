"""
Check the sample output against the original MOMENT implementation.

The script clones the momentfm repository, downloads the MOMENT-1-large weights
from Hugging Face, and reconstructs the time series in sample_data/data.csv with the
original momentfm model, using the same windowing as the container. The reconstructions
are then compared with sample_output/data.csv.out, which was generated by the container
with the model in container/modules.py.

Usage:
    uv run testing.py
"""

import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from huggingface_hub import snapshot_download

ROOT = Path(__file__).resolve().parent
MOMENT_REPO_URL = "https://github.com/moment-timeseries-foundation-model/moment"
MOMENT_REPO_DIR = ROOT / "moment"  # ignored by git
MOMENT_MODEL_ID = "AutonLab/MOMENT-1-large"

# The windowing of the container: overlapping windows, averaged at each time step
sys.path.insert(0, str(ROOT / "container"))
from inference import device, reconstruct

# The sample output can come from different hardware (GPU) than this run, so the
# reconstructions are only expected to agree up to float32 rounding
RTOL = 1e-3
ATOL = 1e-3


class OriginalMOMENT(torch.nn.Module):
    """
    The original momentfm model, with the interface of the model in container/modules.py:
    [batch_size x n_channels x seq_len] -> [batch_size x n_channels x seq_len].
    """

    def __init__(self, model: torch.nn.Module):
        super().__init__()
        self.model = model

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # `reconstruct` reconstructs the full window, as in momentfm's anomaly detection,
        # while the model's forward pass hides random patches, as in pretraining
        return self.model.reconstruct(
            x_enc=x,
            input_mask=torch.ones(x.shape[0], x.shape[-1], device=x.device),
        ).reconstruction


def load_model() -> torch.nn.Module:
    """
    Clone the momentfm repository, download the weights and load the original model.
    """
    if not MOMENT_REPO_DIR.exists():
        subprocess.run(
            ["git", "clone", "--depth", "1", MOMENT_REPO_URL, str(MOMENT_REPO_DIR)],
            check=True,
        )

    # Import momentfm from the clone, not from an installed package
    sys.path.insert(0, str(MOMENT_REPO_DIR))
    from momentfm import MOMENTPipeline

    # The weights are stored in the Hugging Face cache, and downloaded only once
    weights_dir = snapshot_download(
        repo_id=MOMENT_MODEL_ID,
        allow_patterns=["config.json", "model.safetensors"],
    )

    model = MOMENTPipeline.from_pretrained(
        weights_dir,
        model_kwargs={"task_name": "reconstruction"},
    )
    model.init()

    return OriginalMOMENT(model).to(device).eval()


def main() -> int:
    model = load_model()

    # The sample data, in the row order of the sample output: by id, then by timestamp
    actual = pd.read_csv(ROOT / "sample_data" / "data.csv", dtype={"id": str})
    actual = actual.sort_values(["id", "timestamp"]).reset_index(drop=True)
    expected = pd.read_csv(ROOT / "sample_output" / "data.csv.out", dtype={"id": str})

    # The sample output must contain the same rows as the sample data
    columns = ["id", "timestamp", "value"]
    pd.testing.assert_frame_equal(actual[columns], expected[columns])

    # Reconstruct each time series with the original model, using the container's windowing
    series = {
        id: torch.tensor(value.to_numpy())
        for id, value in actual.groupby("id", sort=False)["value"]
    }
    actual["reconstruction"] = torch.cat(reconstruct(model, series)).numpy()

    # Compare the reconstructions of each time series
    print(f"\n{'id':<6}{'rows':>6}{'max abs diff':>16}{'mean abs diff':>16}{'match':>8}")
    passed = True
    for id in actual["id"].unique():
        a = actual.loc[actual["id"] == id, "reconstruction"].to_numpy()
        e = expected.loc[expected["id"] == id, "reconstruction"].to_numpy()
        diff = np.abs(a - e)
        match = np.allclose(a, e, rtol=RTOL, atol=ATOL)
        passed &= match
        print(f"{id:<6}{len(diff):>6}{diff.max():>16.6f}{diff.mean():>16.6f}{'yes' if match else 'NO':>8}")

    print(f"\n{'PASSED' if passed else 'FAILED'} (rtol={RTOL}, atol={ATOL}, device={device})")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
